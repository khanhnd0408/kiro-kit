"""Tab completion for bash, zsh and fish, generated from the real command parser.

Press Tab after `crewctl` to see the commands (zsh and fish also show a one-line description of each), after a command to
see its options, and after `--target` or a workspace/server argument to see the names that exist in your config.
The scripts ask `crewctl values KIND` for those names, so they are always current.
"""

import argparse
import re

from .guide import SOURCES, SOURCES_BY_COMMAND, _args_of


class Node:
    def __init__(self, name, help_text, parser):
        self.name, self.help, self.parser = name, help_text, parser
        self.children = []                      # Node
        self.args = _args_of(parser, skip=("extra",)) if parser else []

    @property
    def path(self):
        return getattr(self, "_path", ())


def build_tree(parser):
    root = Node("", "", parser)
    root._path = ()

    def fill(node):
        subs = [a for a in node.parser._actions if isinstance(a, argparse._SubParsersAction)]
        if not subs:
            return
        helps = {a.dest: (a.help or "") for a in subs[0]._choices_actions}
        for name, sub in subs[0].choices.items():
            if name == "values" or name.startswith("_"):          # the hidden helper that prints names
                continue
            child = Node(name, helps.get(name, ""), sub)
            child._path = node.path + (name,)
            node.children.append(child)
            fill(child)
    fill(root)
    return root


def walk(node):
    yield node
    for child in node.children:
        yield from walk(child)


PATH_DESTS = {"paths", "project", "reference_source", "config_dir", "agents_dir", "crew_home"}


def value_kind(node, arg):
    if arg.dest in PATH_DESTS:
        return "path"                                    # file names, completed by the shell itself
    return SOURCES_BY_COMMAND.get(node.path + (arg.dest,)) or SOURCES.get(arg.dest)


def one_line(text):
    return " ".join((text or "").split())


def positional_choices(node):
    for arg in node.args:
        if arg.positional and arg.choices:
            return [str(c) for c in arg.choices]
    return []


def option_words(node):
    words = ["--help"]
    for arg in node.args:
        words += arg.flags
    return words


# ------------------------------------------------------------------ bash
def bash_script(parser):
    root = build_tree(parser)
    lines = ["# bash completion for crewctl (generated by `crewctl completion bash`)",
             "# Use:  source <(crewctl completion bash)", "",
             "_crewctl_has_sub() {", '  case "$1|$2" in']
    for node in walk(root):
        for child in node.children:
            lines.append(f'    "{" ".join(node.path)}|{child.name}") return 0 ;;')
    lines += ["  esac", "  return 1", "}", "", "_crewctl_subs() {", '  case "$1" in']
    for node in walk(root):
        if node.children:
            lines.append(f'    "{" ".join(node.path)}") echo "{" ".join(c.name for c in node.children)}" ;;')
    lines += ["  esac", "}", "", "_crewctl_opts() {", '  case "$1" in']
    for node in walk(root):
        if not node.children:
            lines.append(f'    "{" ".join(node.path)}") echo "{" ".join(option_words(node))}" ;;')
    lines += ["  esac", "}", "", "_crewctl_value_kind() {", '  # $1 = command path, $2 = the word before the one being completed', '  case "$1|$2" in']
    for node in walk(root):
        for arg in node.args:
            kind = value_kind(node, arg)
            if kind and not arg.positional:
                for flag in arg.flags:
                    lines.append(f'    "{" ".join(node.path)}|{flag}") echo {kind} ;;')
    lines += ["  esac", "}", "", "_crewctl_positional_kind() {", '  case "$1" in']
    for node in walk(root):
        kinds = [value_kind(node, a) for a in node.args if a.positional and value_kind(node, a)]
        if kinds and not node.children:
            lines.append(f'    "{" ".join(node.path)}") echo {kinds[0]} ;;')
    lines += ["  esac", "}", "", "_crewctl_choices() {", '  case "$1" in']
    for node in walk(root):
        choices = positional_choices(node)
        if choices and not node.children:
            lines.append(f'    "{" ".join(node.path)}") echo "{" ".join(choices)}" ;;')
    lines += ["  esac", "}", "",
              "_crewctl() {",
              "  local cur prev path w i kind",
              '  cur="${COMP_WORDS[COMP_CWORD]}"',
              '  prev="${COMP_WORDS[COMP_CWORD-1]}"',
              '  path=""',
              "  for ((i = 1; i < COMP_CWORD; i++)); do",
              '    w="${COMP_WORDS[i]}"',
              '    if _crewctl_has_sub "$path" "$w"; then path="${path:+$path }$w"; fi',
              "  done",
              '  kind="$(_crewctl_value_kind "$path" "$prev")"',
              '  if [ "$kind" = path ]; then COMPREPLY=($(compgen -f -- "$cur")); return 0; fi',
              '  if [ -n "$kind" ]; then',
              '    COMPREPLY=($(compgen -W "$(crewctl values "$kind" 2>/dev/null)" -- "$cur"))',
              "    return 0",
              "  fi",
              '  local subs; subs="$(_crewctl_subs "$path")"',
              '  if [ -n "$subs" ]; then',
              '    COMPREPLY=($(compgen -W "$subs" -- "$cur"))',
              "    return 0",
              "  fi",
              '  local choices; choices="$(_crewctl_choices "$path")"',
              '  if [ -n "$choices" ] && [[ "$cur" != -* ]]; then',
              '    local have=0; for w in "${COMP_WORDS[@]:1:$COMP_CWORD-1}"; do case " $choices " in *" $w "*) have=1 ;; esac; done',
              '    if [ "$have" = 0 ]; then COMPREPLY=($(compgen -W "$choices" -- "$cur")); return 0; fi',
              "  fi",
              '  if [[ "$cur" == -* ]]; then',
              '    COMPREPLY=($(compgen -W "$(_crewctl_opts "$path")" -- "$cur"))',
              "    return 0",
              "  fi",
              '  kind="$(_crewctl_positional_kind "$path")"',
              '  if [ "$kind" = path ]; then',
              '    COMPREPLY=($(compgen -f -- "$cur"))',
              '  elif [ -n "$kind" ]; then',
              '    COMPREPLY=($(compgen -W "$(crewctl values "$kind" 2>/dev/null)" -- "$cur"))',
              "  else",
              '    COMPREPLY=($(compgen -W "$(_crewctl_opts "$path")" -- "$cur"))',
              "  fi",
              "}",
              "complete -F _crewctl crewctl", ""]
    return "\n".join(lines)


# ------------------------------------------------------------------ zsh
def zsh_escape(text):
    """Text for the description half of a `name:description` item. Only the first colon splits, so colons stay as they are."""
    return one_line(text).replace("\\", "\\\\").replace("'", "'\\''")


def zsh_script(parser):
    root = build_tree(parser)
    out = ["#compdef crewctl", "# zsh completion for crewctl (generated by `crewctl completion zsh`)",
           "# Use:  source <(crewctl completion zsh)   (after compinit)  or save as a file named _crewctl in your $fpath", "",
           "_crewctl_has_sub() {", '  case "$1|$2" in']
    for node in walk(root):
        for child in node.children:
            out.append(f'    "{" ".join(node.path)}|{child.name}") return 0 ;;')
    out += ["  esac", "  return 1", "}", "", "_crewctl() {",
            "  local path='' w i kind prev",
            "  local -a items",
            "  for (( i = 2; i < CURRENT; i++ )); do",
            "    w=$words[i]",
            '    if _crewctl_has_sub "$path" "$w"; then path="${path:+$path }$w"; fi',
            "  done",
            "  prev=$words[CURRENT-1]",
            '  case "$path|$prev" in']
    for node in walk(root):
        for arg in node.args:
            kind = value_kind(node, arg)
            if kind and not arg.positional:
                for flag in arg.flags:
                    action = "_files" if kind == "path" else f'compadd -- ${{(f)"$(crewctl values {kind} 2>/dev/null)"}}'
                    out.append(f'    "{" ".join(node.path)}|{flag}") {action}; return ;;')
    out += ["  esac", '  case "$path" in']
    for node in walk(root):
        key = " ".join(node.path)
        if node.children:
            entries = " ".join(f"'{c.name}:{zsh_escape(c.help)}'" for c in node.children)
            out.append(f'    "{key}") items=({entries}); _describe -t commands "crewctl command" items ;;')
        else:
            flags = [("--help", "show the help for this command")] + [(f, a.help) for a in node.args if not a.positional for f in a.flags]
            entries = " ".join(f"'{f}:{zsh_escape(h)}'" for f, h in flags)
            kinds = [value_kind(node, a) for a in node.args if a.positional and value_kind(node, a)]
            if kinds and kinds[0] == "path":
                extra = " [[ $PREFIX != -* ]] && _files;"
            else:
                extra = f' [[ $PREFIX != -* ]] && compadd -- ${{(f)"$(crewctl values {kinds[0]} 2>/dev/null)"}};' if kinds else ""
            choices = positional_choices(node)
            if choices:
                extra += f' [[ $PREFIX != -* ]] && compadd -- {" ".join(choices)};'
            out.append(f'    "{key}") items=({entries});{extra} [[ $PREFIX == -* || -z "$PREFIX" ]] && _describe -t options "option" items ;;')
    out += ["  esac", "}", "", 'compdef _crewctl crewctl', ""]
    return "\n".join(out)


# ------------------------------------------------------------------ fish
def fish_escape(text):
    return one_line(text).replace("\\", "\\\\").replace("'", "\\'")


def fish_script(parser):
    root = build_tree(parser)
    out = ["# fish completion for crewctl (generated by `crewctl completion fish`)",
           "# Use:  crewctl completion fish | source      or save it as ~/.config/fish/completions/crewctl.fish", "",
           "complete -c crewctl -f"]

    def seen(node):
        return " ; and ".join(f"__fish_seen_subcommand_from {w}" for w in node.path) if node.path else "__fish_use_subcommand"

    for node in walk(root):
        if node.children:
            names = " ".join(c.name for c in node.children)
            cond = (seen(node) + f" ; and not __fish_seen_subcommand_from {names}") if node.path else "__fish_use_subcommand"
            for child in node.children:
                out.append(f"complete -c crewctl -n '{cond}' -a '{child.name}' -d '{fish_escape(child.help)}'")
        else:
            cond = seen(node)
            choices = positional_choices(node)
            if choices:
                out.append(f"complete -c crewctl -n '{cond} ; and not __fish_seen_subcommand_from {' '.join(choices)}' -a '{' '.join(choices)}'")
            for arg in node.args:
                if arg.positional:
                    kind = value_kind(node, arg)
                    if kind == "path":
                        out.append(f"complete -c crewctl -n '{cond}' -F")
                    elif kind:
                        out.append(f"complete -c crewctl -n '{cond}' -a '(crewctl values {kind} 2>/dev/null)'")
                    continue
                for flag in arg.flags:
                    long = flag.startswith("--")
                    option = f"-l {flag[2:]}" if long else f"-s {flag[1:]}"
                    kind = value_kind(node, arg)
                    value = ((" -r -F" if kind == "path" else " -x" + (f" -a '(crewctl values {kind} 2>/dev/null)'" if kind else
                                      (" -a '" + " ".join(map(str, arg.choices)) + "'" if arg.choices else "")))) if arg.kind != "flag" else ""
                    out.append(f"complete -c crewctl -n '{cond}' {option}{value} -d '{fish_escape(arg.help)}'")
    return "\n".join(out) + "\n"


SCRIPTS = {"bash": bash_script, "zsh": zsh_script, "fish": fish_script}
